def _resolve_ffmpeg_exe():
    found = shutil.which("ffmpeg")
    if found:
        return found

    local_bin_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "bin")
    local_bin = os.path.join(local_bin_dir, "ffmpeg.exe")
    if os.path.exists(local_bin):
        return local_bin

    # Buscar instalación de WinGet (Gyan.FFmpeg) aunque no se haya reiniciado Chrome
    local_app = os.environ.get("LOCALAPPDATA", "")
    if local_app:
        winget_dir = os.path.join(local_app, "Microsoft", "WinGet", "Packages")
        if os.path.isdir(winget_dir):
            for root, _, files in os.walk(winget_dir):
                if "ffmpeg.exe" in files and "Gyan.FFmpeg" in root:
                    return os.path.join(root, "ffmpeg.exe")

    # Respaldo universal: imageio-ffmpeg (instalado por instalar.bat)
    try:
        import imageio_ffmpeg
        src_exe = imageio_ffmpeg.get_ffmpeg_exe()
        if src_exe and os.path.exists(src_exe):
            os.makedirs(local_bin_dir, exist_ok=True)
            shutil.copy2(src_exe, local_bin)
            return local_bin
    except Exception:
        pass

    return "ffmpeg.exe"


PYTHON_EXE = sys.executable
FFMPEG_EXE = _resolve_ffmpeg_exe()
FFMPEG_DIR = os.path.dirname(FFMPEG_EXE) if os.path.isabs(FFMPEG_EXE) else ""
NODE_EXE = shutil.which("node") or ""
LOG_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "omnistream_host.log")

stdout_lock = threading.Lock()
log_lock = threading.Lock()
active_processes = {}


def append_log(message):
    """Registra eventos y errores del puente nativo en omnistream_host.log."""
    try:
        with log_lock:
            if os.path.exists(LOG_FILE) and os.path.getsize(LOG_FILE) > 512 * 1024:
                with open(LOG_FILE, "w", encoding="utf-8") as f:
                    f.write(f"[{time.strftime('%Y-%m-%d %H:%M:%S')}] Log rotado por tamaño.\n")
            with open(LOG_FILE, "a", encoding="utf-8") as f:
                f.write(f"[{time.strftime('%Y-%m-%d %H:%M:%S')}] {message}\n")
    except Exception:
        pass


def send_native_message(payload):
    """Envía un mensaje JSON codificado con cabecera uint32 little-endian a Chrome."""
    try:
        raw_bytes = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        header = struct.pack("<I", len(raw_bytes))
        with stdout_lock:
            sys.stdout.buffer.write(header)
            sys.stdout.buffer.write(raw_bytes)
            sys.stdout.buffer.flush()
    except Exception:
        pass


def read_native_message():
    """Lee un mensaje JSON desde stdin enviado por Chrome."""
    raw_len = sys.stdin.buffer.read(4)
    if not raw_len or len(raw_len) < 4:
        return None
    msg_len = struct.unpack("<I", raw_len)[0]
    if msg_len <= 0:
        return None
    data = sys.stdin.buffer.read(msg_len)
    if not data:
        return None
    return json.loads(data.decode("utf-8", errors="replace"))


def sanitize_filename(name):
    if not name:
        return f"video_{int(time.time())}"
    cleaned = re.sub(r'[/\\?%*:|"<>]', " ", str(name))
    cleaned = re.sub(r"\s+", " ", cleaned).strip()
    cleaned = cleaned.rstrip(". ")
    return cleaned or f"video_{int(time.time())}"


def build_netscape_cookies_file(cookies_list):
    """Convierte las cookies de chrome.cookies.getAll al formato Netscape requerido por yt-dlp."""
    if not cookies_list or not isinstance(cookies_list, list):
        return None
    try:
        fd, temp_path = tempfile.mkstemp(prefix="omnistream_cookies_", suffix=".txt", text=True)
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write("# Netscape HTTP Cookie File\n")
            f.write("# Generated by OmniStream Native Bridge\n\n")
            for c in cookies_list:
                domain = c.get("domain", "")
                if not domain:
                    continue
                include_sub = "TRUE" if domain.startswith(".") else "FALSE"
                path = c.get("path", "/")
                secure = "TRUE" if c.get("secure") else "FALSE"
                expiry = int(c.get("expirationDate") or (time.time() + 86400 * 30))
                name = c.get("name", "")
                value = c.get("value", "")
                if not name:
                    continue
                f.write(f"{domain}\t{include_sub}\t{path}\t{secure}\t{expiry}\t{name}\t{value}\n")
        return temp_path
    except Exception:
        return None


def get_downloads_dir():
    user_profile = os.environ.get("USERPROFILE") or str(Path.home())
    dl_dir = os.path.join(user_profile, "Downloads")
    if not os.path.isdir(dl_dir):
        os.makedirs(dl_dir, exist_ok=True)
    return dl_dir


def resolve_unique_filepath(directory, base_name, ext):
    candidate = os.path.join(directory, f"{base_name}.{ext}")
    if not os.path.exists(candidate):
        return candidate
    counter = 1
    while True:
        candidate = os.path.join(directory, f"{base_name} ({counter}).{ext}")
        if not os.path.exists(candidate):
            return candidate
        counter += 1


def get_gemini_api_key():
    """Obtiene GEMINI_API_KEY desde entorno o Registro de usuario Windows."""
    key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    if key:
        return key.strip()
    if sys.platform == "win32":
        try:
            import winreg
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, r"Environment") as reg_key:
                for name in ("GEMINI_API_KEY", "GOOGLE_API_KEY"):
                    try:
                        val, _ = winreg.QueryValueEx(reg_key, name)
                        if val:
                            return str(val).strip()
                    except FileNotFoundError:
                        continue
        except Exception:
            pass
    return ""


def transcribe_audio_with_gemini(mp3_path, raw_title, course_context, download_id, media_id):
    """Sube el MP3 ligero a Gemini y genera una transcripción interpretada en Markdown."""
    api_key = get_gemini_api_key()
    if not api_key:
        raise RuntimeError("Falta GEMINI_API_KEY en el entorno de Windows.")

    from google import genai
    client = genai.Client(api_key=api_key)

    send_native_message({
        "type": "progress",
        "downloadId": download_id,
        "mediaId": media_id,
        "audioOnly": True,
        "transcribeOnly": True,
        "percent": 88,
        "statusMessage": "Subiendo audio a Gemini 3.5 Flash-Lite..."
    })

    uploaded = client.files.upload(file=mp3_path)
    try:
        while getattr(uploaded, "state", None) and str(uploaded.state).upper().endswith("PROCESSING"):
            time.sleep(1.5)
            uploaded = client.files.get(name=uploaded.name)

        send_native_message({
            "type": "progress",
            "downloadId": download_id,
            "mediaId": media_id,
            "audioOnly": True,
            "transcribeOnly": True,
            "percent": 94,
            "statusMessage": "Transcribiendo con Gemini 3.5 Flash-Lite..."
        })

        ctx_line = f"Contexto / Ramo / Tema: {course_context}\n" if course_context else ""
        prompt = (
            "Eres un transcriptor académico experto en español de Chile.\n"
            f"Título del material: {raw_title}\n"
            f"{ctx_line}\n"
            "Instrucciones estrictas:\n"
            "1. Entrega primero un encabezado breve con el resumen de lo tratado.\n"
            "2. Luego entrega la **transcripción literal completa, palabra por palabra**, de todo el audio en el idioma hablado (o en español si el audio está en español), en orden cronológico y con marcas de tiempo `[MM:SS]` cada vez que cambie de idea o cada ~30-60 segundos.\n"
            "3. PROHIBIDO resumir, parafrasear, compactar u omitir frases en la sección de Transcripción Literal. Debes transcribir exactamente todo lo que se dice de principio a fin. Si el hablante tiene mala dicción o pronuncia mal un término técnico, escribe la palabra técnica correcta según el contexto del tema manteniendo intacta su frase original.\n"
            "4. Usa exactamente esta estructura Markdown:\n"
            f"# {raw_title}\n\n"
            "## Resumen\n"
            "<Síntesis clara y concisa de los temas y puntos clave del audio>\n\n"
            "## Transcripción Literal\n"
            "<Transcripción íntegra palabra por palabra con marcas [MM:SS]>\n"
        )

        mime = getattr(uploaded, "mime_type", None) or "audio/mpeg"
        chunks = []
        word_count = 0
        last_notify_len = 0

        stream = client.interactions.create(
            model="gemini-3.5-flash-lite",
            input=[
                {"type": "text", "text": prompt},
                {"type": "audio", "uri": uploaded.uri, "mime_type": mime}
            ],
            stream=True,
            store=False
        )
        for ev in stream:
            delta = getattr(ev, "delta", None)
            chunk_text = getattr(delta, "text", None) if delta else None
            if chunk_text:
                chunks.append(chunk_text)
                total_len = sum(len(c) for c in chunks)
                if total_len - last_notify_len >= 400:
                    last_notify_len = total_len
                    word_count = len("".join(chunks).split())
                    pct = min(99, 94 + min(5, total_len // 2000))
                    send_native_message({
                        "type": "progress",
                        "downloadId": download_id,
                        "mediaId": media_id,
                        "audioOnly": True,
                        "transcribeOnly": True,
                        "percent": pct,
                        "statusMessage": f"Transcribiendo con Flash-Lite ({word_count} palabras)..."
                    })

        text = "".join(chunks).strip()
        if not text:
            raise RuntimeError("Gemini no devolvió texto de transcripción.")
        return text
    finally:
        try:
            client.files.delete(name=uploaded.name)
        except Exception:
            pass


def _execute_ytdlp_cmd(cmd, download_id, media_id, audio_only, audio_kbps):
    """Ejecuta yt-dlp transmitiendo progreso a Chrome y capturando el último error."""
    creation_flags = subprocess.CREATE_NO_WINDOW if sys.platform == "win32" else 0
    proc = subprocess.Popen(
        cmd,
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding="utf-8",
        errors="replace",
        creationflags=creation_flags
    )
    active_processes[download_id] = proc

    pct_regex = re.compile(r"\[download\]\s+(\d+(?:\.\d+)?)%")
    stage_track = 0  # 0 = video, 1 = audio
    last_error = ""

    for raw_line in proc.stdout:
        line = raw_line.strip()
        if not line:
            continue

        append_log(f"[{download_id}] {line}")
        if line.startswith("ERROR:"):
            last_error = line[len("ERROR:"):].strip()

        if "[download] Destination:" in line:
            stage_track += 1

        m = pct_regex.search(line)
        if m:
            raw_pct = float(m.group(1))
            if audio_only:
                scaled = int(5 + raw_pct * 0.80)
                msg_text = f"Descargando pista de audio: {raw_pct:.1f}%"
            else:
                if stage_track <= 1:
                    scaled = int(5 + raw_pct * 0.45)
                    msg_text = f"Descargando pista de Video: {raw_pct:.1f}%"
                else:
                    scaled = int(50 + raw_pct * 0.40)
                    msg_text = f"Descargando pista de Audio: {raw_pct:.1f}%"

            send_native_message({
                "type": "progress",
                "downloadId": download_id,
                "mediaId": media_id,
                "audioOnly": audio_only,
                "percent": min(94, max(3, scaled)),
                "statusMessage": msg_text
            })
        elif "[Merger]" in line or "Merging formats" in line:
            send_native_message({
                "type": "progress",
                "downloadId": download_id,
                "mediaId": media_id,
                "audioOnly": audio_only,
                "percent": 95,
                "statusMessage": "Fusionando Video + Audio con FFmpeg..."
            })
        elif "[ExtractAudio]" in line:
            send_native_message({
                "type": "progress",
                "downloadId": download_id,
                "mediaId": media_id,
                "audioOnly": audio_only,
                "percent": 94,
                "statusMessage": f"Codificando a .MP3 ({audio_kbps} kbps) con FFmpeg..."
            })

    ret_code = proc.wait()
    active_processes.pop(download_id, None)
    return ret_code, last_error


def _build_ytdlp_cmd(url, temp_out_tmpl, audio_only, video_quality, audio_kbps, cookies_file, headers_dict, page_url, is_youtube):
    """Construye la línea de comandos de yt-dlp con JS runtime y selección de formatos."""
    cmd = [
        PYTHON_EXE, "-m", "yt_dlp",
        "--no-playlist",
        "--no-update",
        "--newline",
        "--no-colors",
        "--progress",
        "-o", temp_out_tmpl
    ]

    if FFMPEG_DIR and os.path.isdir(FFMPEG_DIR):
        cmd.extend(["--ffmpeg-location", FFMPEG_DIR])

    if os.path.exists(NODE_EXE):
        cmd.extend(["--js-runtimes", f"node:{NODE_EXE}"])

    if cookies_file and os.path.exists(cookies_file):
        cmd.extend(["--cookies", cookies_file])

    if not is_youtube:
        referer = headers_dict.get("Referer") or headers_dict.get("referer") or page_url
        if referer:
            cmd.extend(["--referer", referer])

    if audio_only:
        kbps_str = f"{audio_kbps}K"
        cmd.extend([
            "-f", "bestaudio/best",
            "-x",
            "--audio-format", "mp3",
            "--audio-quality", kbps_str
        ])
    else:
        if video_quality < 9000:
            fmt = (
                f"bestvideo[height<={video_quality}][vcodec^=avc1]+bestaudio[acodec^=mp4a]/"
                f"bestvideo[height<={video_quality}][ext=mp4]+bestaudio[ext=m4a]/"
                f"bestvideo[height<={video_quality}]+bestaudio/"
                f"best[height<={video_quality}]/best"
            )
        else:
            fmt = (
                "bestvideo[vcodec^=avc1]+bestaudio[acodec^=mp4a]/"
                "bestvideo[ext=mp4]+bestaudio[ext=m4a]/"
                "bestvideo+bestaudio/best"
            )
        cmd.extend([
            "-f", fmt,
            "--merge-output-format", "mp4",
            "--postprocessor-args", "Merger+ffmpeg:-c:v copy -c:a aac -b:a 192k"
        ])

    cmd.append(url)
    return cmd


def prompt_save_path(initial_dir, initial_filename, target_ext):
    """Abre el cuadro nativo Guardar como de Windows en un subproceso aislado."""
    ext_labels = {
        "mp4": ("Video MP4", "*.mp4"),
        "mp3": ("Audio MP3", "*.mp3"),
        "md": ("Apuntes Markdown", "*.md")
    }
    label, pattern = ext_labels.get(target_ext, (f"Archivo {target_ext.upper()}", f"*.{target_ext}"))
    script = (
        "import sys, tkinter as tk, tkinter.filedialog as fd; "
        "r = tk.Tk(); r.withdraw(); r.attributes('-topmost', True); r.update(); "
        "p = fd.asksaveasfilename(parent=r, title='Guardar archivo con OmniStream', "
        "initialdir=sys.argv[1], initialfile=sys.argv[2], defaultextension=sys.argv[3], "
        "filetypes=[(sys.argv[4], sys.argv[5]), ('Todos los archivos', '*.*')]); "
        "r.destroy(); print(p or '', end='')"
    )
    creation_flags = subprocess.CREATE_NO_WINDOW if sys.platform == "win32" else 0
    res = subprocess.run(
        [PYTHON_EXE, "-c", script, initial_dir, initial_filename, f".{target_ext}", label, pattern],
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        encoding="utf-8",
        errors="replace",
        creationflags=creation_flags
    )
    chosen = (res.stdout or "").strip()
    if not chosen:
        return ""
    chosen = os.path.normpath(chosen)
    if not chosen.lower().endswith(f".{target_ext}"):
        chosen = f"{chosen}.{target_ext}"
    return chosen


def run_ytdlp_task(task):
    download_id = task.get("downloadId", f"dl_{int(time.time())}")
    media_id = task.get("mediaId", "yt_media")
    url = task.get("url", "")
    raw_title = task.get("title") or task.get("filename") or "Video"
    transcribe_only = bool(task.get("transcribeOnly", False))
    course_context = (task.get("courseContext") or "").strip()
    audio_only = True if transcribe_only else bool(task.get("audioOnly", False))
    quality_opts = task.get("qualityOptions") or {}
    video_quality = int(quality_opts.get("videoQuality") or 9999)
    audio_kbps = 64 if transcribe_only else int(quality_opts.get("audioKbps") or 128)
    cookies_list = task.get("cookies") or []
    headers_dict = task.get("headers") or {}

    base_title = re.sub(r"\.(mp4|mp3|m3u8|mpd|webm|ts|mkv)$", "", raw_title, flags=re.IGNORECASE)
    clean_base = sanitize_filename(base_title)
    target_ext = "md" if transcribe_only else ("mp3" if audio_only else "mp4")
    ytdlp_ext = "mp3" if audio_only else "mp4"
    downloads_dir = get_downloads_dir()
    suggested_path = resolve_unique_filepath(downloads_dir, clean_base, target_ext)

    if task.get("skipSaveDialog"):
        final_output_path = suggested_path
    else:
        chosen_path = prompt_save_path(downloads_dir, os.path.basename(suggested_path), target_ext)
        if not chosen_path:
            append_log(f"[{download_id}] Cancelado por el usuario en diálogo Guardar como.")
            send_native_message({
                "type": "cancelled",
                "downloadId": download_id,
                "mediaId": media_id
            })
            return
        parent_dir = os.path.dirname(chosen_path)
        if parent_dir and not os.path.isdir(parent_dir):
            os.makedirs(parent_dir, exist_ok=True)
        final_output_path = chosen_path

    temp_dir = tempfile.mkdtemp(prefix="omnistream_dl_")
    temp_out_tmpl = os.path.join(temp_dir, "output.%(ext)s")
    cookies_file = build_netscape_cookies_file(cookies_list)
    is_youtube = ("youtube.com" in url.lower() or "youtu.be" in url.lower())

    try:
        if not FFMPEG_DIR or not os.path.exists(FFMPEG_EXE):
            raise RuntimeError("Falta FFmpeg: ejecuta instalar.bat para instalarlo automáticamente.")

        append_log(f"[{download_id}] Inicio tarea: url={url} audioOnly={audio_only} transcribeOnly={transcribe_only} cookies={len(cookies_list)}")
        send_native_message({
            "type": "progress",
            "downloadId": download_id,
            "mediaId": media_id,
            "audioOnly": audio_only,
            "transcribeOnly": transcribe_only,
            "percent": 3,
            "statusMessage": "Extrayendo audio para Gemini..." if transcribe_only else "Conectando con motor yt-dlp + FFmpeg 9.0..."
        })

        cmd = _build_ytdlp_cmd(
            url, temp_out_tmpl, audio_only, video_quality, audio_kbps,
            cookies_file, headers_dict, task.get("pageUrl"), is_youtube
        )
        ret_code, last_error = _execute_ytdlp_cmd(cmd, download_id, media_id, audio_only, audio_kbps)

        # En YouTube, si el intento con cookies de Chrome falla, reintentar sin cookies (clientes alternativos)
        if ret_code != 0 and is_youtube and cookies_file:
            append_log(f"[{download_id}] Falló con cookies (código {ret_code}). Reintentando sin cookies...")
            send_native_message({
                "type": "progress",
                "downloadId": download_id,
                "mediaId": media_id,
                "audioOnly": audio_only,
                "transcribeOnly": transcribe_only,
                "percent": 3,
                "statusMessage": "Reintentando extracción sin cookies de sesión..."
            })
            for f in os.listdir(temp_dir):
                try:
                    os.remove(os.path.join(temp_dir, f))
                except Exception:
                    pass
            cmd_no_cookies = _build_ytdlp_cmd(
                url, temp_out_tmpl, audio_only, video_quality, audio_kbps,
                None, headers_dict, task.get("pageUrl"), is_youtube
            )
            ret_code, last_error = _execute_ytdlp_cmd(cmd_no_cookies, download_id, media_id, audio_only, audio_kbps)

        generated_files = [
            os.path.join(temp_dir, f)
            for f in os.listdir(temp_dir)
            if f.lower().endswith(f".{ytdlp_ext}")
        ]
        if not generated_files:
            generated_files = [
                os.path.join(temp_dir, f)
                for f in os.listdir(temp_dir)
                if not f.endswith(".part") and not f.endswith(".ytdl")
            ]

        if ret_code != 0 or not generated_files:
            detail = f": {last_error[:180]}" if last_error else f" (código {ret_code})."
            raise RuntimeError(f"No se pudo extraer el flujo con yt-dlp{detail}")

        produced_file = generated_files[0]
        if transcribe_only:
            md_content = transcribe_audio_with_gemini(
                produced_file, clean_base, course_context, download_id, media_id
            )
            with open(final_output_path, "w", encoding="utf-8") as f:
                f.write(md_content)
        else:
            shutil.move(produced_file, final_output_path)

        file_size = os.path.getsize(final_output_path)
        append_log(f"[{download_id}] Completado: {final_output_path} ({file_size} bytes)")

        send_native_message({
            "type": "completed",
            "downloadId": download_id,
            "mediaId": media_id,
            "audioOnly": audio_only,
            "transcribeOnly": transcribe_only,
            "filepath": final_output_path,
            "filename": os.path.basename(final_output_path),
            "sizeBytes": file_size,
            "percent": 100,
            "statusMessage": f"¡Transcripción guardada: {os.path.basename(final_output_path)}!" if transcribe_only else f"¡Guardado en Descargas: {os.path.basename(final_output_path)}!"
        })

    except Exception as exc:
        active_processes.pop(download_id, None)
        append_log(f"[{download_id}] ERROR FINAL: {exc}")
        send_native_message({
            "type": "error",
            "downloadId": download_id,
            "mediaId": media_id,
            "audioOnly": audio_only,
            "transcribeOnly": transcribe_only,
            "error": str(exc)
        })
    finally:
        if cookies_file and os.path.exists(cookies_file):
            try:
                os.remove(cookies_file)
            except Exception:
                pass
        if os.path.isdir(temp_dir):
            try:
                shutil.rmtree(temp_dir, ignore_errors=True)
            except Exception:
                pass


def probe_formats(task):
    """Consulta las resoluciones disponibles y miniatura real del video mediante yt-dlp -J."""
    url = task.get("url", "")
    media_id = task.get("mediaId", "")
    tab_id = task.get("tabId")
    cookies_list = task.get("cookies") or []
    is_youtube = ("youtube.com" in url.lower() or "youtu.be" in url.lower())
    cookies_file = build_netscape_cookies_file(cookies_list)

    def _run_probe(use_cookies_path):
        cmd = [
            PYTHON_EXE, "-m", "yt_dlp",
            "--no-playlist",
            "--no-update",
            "--no-warnings",
            "-J",
            "--skip-download"
        ]
        if os.path.exists(NODE_EXE):
            cmd.extend(["--js-runtimes", f"node:{NODE_EXE}"])
        if use_cookies_path and os.path.exists(use_cookies_path):
            cmd.extend(["--cookies", use_cookies_path])
        cmd.append(url)
        creation_flags = subprocess.CREATE_NO_WINDOW if sys.platform == "win32" else 0
        return subprocess.run(
            cmd,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            encoding="utf-8",
            errors="replace",
            creationflags=creation_flags,
            timeout=25
        )

    try:
        res = _run_probe(cookies_file)
        if res.returncode != 0 and is_youtube and cookies_file:
            res = _run_probe(None)
        if res.returncode != 0 or not res.stdout.strip():
            return

        info = json.loads(res.stdout)
        formats = info.get("formats") or []
        heights_set = set()
        for f in formats:
            vcodec = f.get("vcodec") or "none"
            h = f.get("height")
            if vcodec != "none" and isinstance(h, int) and h >= 144:
                heights_set.add(h)

        heights = sorted(heights_set, reverse=True)
        send_native_message({
            "type": "formats_result",
            "mediaId": media_id,
            "tabId": tab_id,
            "heights": heights,
            "thumbnail": info.get("thumbnail") or "",
            "title": info.get("title") or ""
        })
    except Exception as exc:
        append_log(f"[probe_formats] Error: {exc}")
    finally:
        if cookies_file and os.path.exists(cookies_file):
            try:
                os.remove(cookies_file)
            except Exception:
                pass


def main():
    while True:
        msg = read_native_message()
        if msg is None:
            break

        action = msg.get("action")
        if action == "ping":
            send_native_message({
                "type": "pong",
                "version": "3.2.3",
                "ffmpeg": os.path.exists(FFMPEG_EXE)
            })
        elif action == "probe_formats":
            t = threading.Thread(target=probe_formats, args=(msg,), daemon=True)
            t.start()
        elif action == "start_native_download":
            t = threading.Thread(target=run_ytdlp_task, args=(msg,), daemon=True)
            t.start()
        elif action == "abort_native_download":
            dl_id = msg.get("downloadId")
            proc = active_processes.pop(dl_id, None)
            if proc:
                try:
                    proc.terminate()
                except Exception:
                    pass
        elif action == "open_file_in_folder":
            filepath = msg.get("filepath")
            if filepath and os.path.exists(filepath):
                norm_path = os.path.normpath(filepath)
                append_log(f"[open_file_in_folder] Abriendo: {norm_path}")
                try:
                    subprocess.Popen(
                        f'explorer.exe /select,"{norm_path}"',
                        stdin=subprocess.DEVNULL,
                        stdout=subprocess.DEVNULL,
                        stderr=subprocess.DEVNULL
                    )
                except Exception as exc:
                    append_log(f"[open_file_in_folder] Error: {exc}")


if __name__ == "__main__":
    main()
